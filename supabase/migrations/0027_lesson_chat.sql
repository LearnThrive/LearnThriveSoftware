-- 0027_lesson_chat.sql — chat and file sharing INSIDE a lesson, and only during it (docs/LESSON_CHAT.md).
--
--   lesson_messages          one row per message, belonging to ONE lesson row. Each occurrence of a recurring lesson is its own row in public.lessons,
--                            so each has its own conversation. Written only by the server, which has already checked who may send and when.
--   lesson_files             the record of a shared file (private storage key, type, size). The BYTES are in a private storage bucket, never public,
--                            and are reached only by a short-lived signed URL the web app issues after a read check.
--   lesson_chat_access_log   append-only: every read by an administrator, the safeguarding lead or a parent, and every administrator's removal.
--
-- What the database enforces by itself (defence in depth: the web app checks first, in one place):
--   * a message can only be added by the lesson's own tutor (who holds the TUTOR role: a junior tutor cannot send) or a student enrolled in it
--     (a learner login bound to that student), never on a cancelled or no-show lesson, and only within an hour either side of the scheduled time
--     (the exact window, including any grace, is the application's; this is the outer limit). The time stored is the database's, not the client's;
--   * a message is never edited, and never deleted by anyone. An administrator's removal only MARKS it (removed_at, removed_by, removal_reason), once;
--   * files and the log are append-only. The one exception to "never deleted" is the cascade of purging a lesson (migration 0018): a purge removes
--     the lesson's messages and file records, and the purge job must also delete the stored files.
--
-- Row-level security: authenticated users may SELECT only (the lesson's tutor and its students, and a parent of a student on the lesson once it has
-- ended). There is NO policy for administrators or the safeguarding lead: they read through the server so that every read is audit-logged, which a
-- policy cannot do. Nobody has INSERT, UPDATE or DELETE through the API.
--
-- Re-runnable. Written as a file: it is applied only on the owner's go-ahead.

-- ---------------------------------------------------------------------------------------------------------------------------------------
-- tables
-- ---------------------------------------------------------------------------------------------------------------------------------------
create table if not exists public.lesson_messages (
  id uuid primary key default gen_random_uuid(),
  lesson_id uuid not null references public.lessons (id) on delete cascade,
  sender_profile_id uuid references public.profiles (id) on delete set null,
  sender_party text not null check (sender_party in ('tutor', 'student')),
  -- The tutor or student record they sent as: what the send was checked against.
  sender_record_id uuid not null,
  sender_name text not null check (char_length(sender_name) <= 80),
  body text not null default '' check (char_length(body) <= 2000),
  created_at timestamptz not null default now(),
  removed_at timestamptz,
  removed_by uuid references public.profiles (id) on delete set null,
  removal_reason text check (removal_reason is null or char_length(removal_reason) between 1 and 300),
  check ((removed_at is null) = (removal_reason is null))
);
create index if not exists lesson_messages_lesson_idx on public.lesson_messages (lesson_id, created_at, id);

create table if not exists public.lesson_files (
  id uuid primary key default gen_random_uuid(),
  lesson_id uuid not null references public.lessons (id) on delete cascade,
  message_id uuid not null unique references public.lesson_messages (id) on delete cascade,
  -- Generated by the server: lessons/<lesson id>/<uuid>.<ext>. Nothing the user sent is in it.
  storage_key text not null unique check (storage_key ~ '^lessons/[A-Za-z0-9_-]{1,80}/[0-9a-f-]{36}\.(png|jpg|pdf)$'),
  content_type text not null check (content_type in ('image/png', 'image/jpeg', 'application/pdf')),
  size_bytes integer not null check (size_bytes between 1 and 26214400),
  -- For display only: never a path.
  display_name text not null check (char_length(display_name) between 1 and 120 and display_name !~ '[/\\:]' and display_name not like '%..%'),
  uploaded_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists lesson_files_lesson_idx on public.lesson_files (lesson_id);

create table if not exists public.lesson_chat_access_log (
  id bigint generated always as identity primary key,
  at timestamptz not null default now(),
  -- No foreign key: the log outlives a purged lesson, and holds no content.
  lesson_id uuid not null,
  actor_profile_id uuid references public.profiles (id) on delete set null,
  actor_kind text not null check (actor_kind in ('admin', 'safeguarding_lead', 'parent')),
  action text not null check (action in ('read_messages', 'read_file', 'remove_message')),
  target_id uuid
);
create index if not exists lesson_chat_access_log_lesson_idx on public.lesson_chat_access_log (lesson_id, at desc);

comment on table public.lesson_messages is 'Lesson chat: one conversation per lesson row (so per occurrence of a recurring lesson). Written only by the server after the send rules; never edited or deleted, only marked removed by an administrator.';
comment on table public.lesson_files is 'A file shared in a lesson. Bytes are in private storage under storage_key and are served only by short-lived signed URLs.';
comment on table public.lesson_chat_access_log is 'Append-only audit of reads by administrators, the safeguarding lead and parents, and of administrators'' removals.';

