-- guards
-- ---------------------------------------------------------------------------------------------------------------------------------------

-- Nothing is deleted directly. A cascade from a purged lesson (or message) runs this trigger one level deeper, and is allowed.
create or replace function private.lesson_chat_no_direct_delete() returns trigger
language plpgsql set search_path = '' as $$
begin
  if pg_trigger_depth() < 2 then
    raise exception '% rows are never deleted (only removed from view by an administrator, or purged with their lesson)', tg_table_name using errcode = 'restrict_violation';
  end if;
  return old;
end;
$$;

create or replace function private.lesson_chat_no_update() returns trigger
language plpgsql set search_path = '' as $$
begin
  -- Only a purged uploader's id may change (to null, by the foreign key).
  if (to_jsonb(new) - 'uploaded_by') is not distinct from (to_jsonb(old) - 'uploaded_by') and new.uploaded_by is null then
    return new;
  end if;
  raise exception '% is append-only', tg_table_name using errcode = 'restrict_violation';
end;
$$;

-- A send: who, to what, when.
create or replace function private.lesson_messages_guard() returns trigger
language plpgsql set search_path = '' as $$
declare
  v_lesson public.lessons%rowtype;
begin
  select * into v_lesson from public.lessons l where l.id = new.lesson_id;
  if not found then
    raise exception 'There is no such lesson.' using errcode = 'foreign_key_violation';
  end if;
  if v_lesson.status in ('CANCELLED', 'NO_SHOW') then
    raise exception 'A cancelled lesson has no chat.' using errcode = 'check_violation';
  end if;
  -- The time is the database's: a message cannot be back-dated or sent ahead. The application enforces the exact window (and any grace);
  -- this is the outer limit, an hour either side.
  new.created_at := now();
  if now() < v_lesson.start_at - interval '60 minutes' or now() >= v_lesson.start_at + make_interval(mins => v_lesson.duration_minutes) + interval '60 minutes' then
    raise exception 'Messages can only be sent during the lesson.' using errcode = 'check_violation';
  end if;

  if new.sender_party = 'tutor' then
    -- The lesson's own tutor record, belonging to the sender, and the sender holds the TUTOR role. A junior tutor (JUNIOR_TUTOR) cannot send.
    if new.sender_record_id is distinct from v_lesson.tutor_id
       or not exists (select 1 from public.tutors t where t.id = v_lesson.tutor_id and t.profile_id = new.sender_profile_id)
       or not exists (select 1 from public.profile_roles r where r.profile_id = new.sender_profile_id and r.role = 'TUTOR') then
      raise exception 'Only the lesson''s tutor can send as its tutor.' using errcode = 'insufficient_privilege';
    end if;
  else
    -- A student enrolled in this lesson, through their own learner login.
    if not exists (select 1 from public.lesson_students ls where ls.lesson_id = new.lesson_id and ls.student_id = new.sender_record_id)
       or not exists (select 1 from public.learner_identities li where li.student_id = new.sender_record_id and li.profile_id = new.sender_profile_id and li.status = 'active')
       or not exists (select 1 from public.profile_roles r where r.profile_id = new.sender_profile_id and r.role = 'STUDENT') then
      raise exception 'Only a student enrolled in this lesson can send as a student.' using errcode = 'insufficient_privilege';
    end if;
  end if;

  if new.removed_at is not null or new.removed_by is not null or new.removal_reason is not null then
    raise exception 'A message is not sent already removed.' using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

-- An update may do exactly one thing: mark a message removed, once, by an administrator. Nothing else about it can change.
create or replace function private.lesson_messages_update_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  -- A person being purged: their foreign keys are set to null. That, and nothing else, is allowed to change a message besides its removal.
  if (to_jsonb(new) - 'sender_profile_id' - 'removed_by') is not distinct from (to_jsonb(old) - 'sender_profile_id' - 'removed_by')
     and (new.sender_profile_id is null or new.sender_profile_id is not distinct from old.sender_profile_id)
     and (new.removed_by is null or new.removed_by is not distinct from old.removed_by) then
    return new;
  end if;
  if old.removed_at is not null then
    raise exception 'That message was already removed.' using errcode = 'restrict_violation';
  end if;
  if (to_jsonb(new) - 'removed_at' - 'removed_by' - 'removal_reason') is distinct from (to_jsonb(old) - 'removed_at' - 'removed_by' - 'removal_reason') then
    raise exception 'A message is never edited.' using errcode = 'restrict_violation';
  end if;
  if new.removed_at is null or new.removed_by is null or not exists (select 1 from public.profile_roles r where r.profile_id = new.removed_by and r.role = 'ADMIN') then
    raise exception 'Only an administrator removes a message.' using errcode = 'insufficient_privilege';
  end if;
  return new;
end;
$$;

-- A file record must belong to the same lesson as its message.
create or replace function private.lesson_files_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  if not exists (select 1 from public.lesson_messages m where m.id = new.message_id and m.lesson_id = new.lesson_id) then
    raise exception 'A file belongs to the lesson of its message.' using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

drop trigger if exists lesson_messages_guard on public.lesson_messages;
create trigger lesson_messages_guard before insert on public.lesson_messages for each row execute function private.lesson_messages_guard();
drop trigger if exists lesson_messages_update_guard on public.lesson_messages;
create trigger lesson_messages_update_guard before update on public.lesson_messages for each row execute function private.lesson_messages_update_guard();
drop trigger if exists lesson_messages_no_delete on public.lesson_messages;
create trigger lesson_messages_no_delete before delete on public.lesson_messages for each row execute function private.lesson_chat_no_direct_delete();

drop trigger if exists lesson_files_guard on public.lesson_files;
create trigger lesson_files_guard before insert on public.lesson_files for each row execute function private.lesson_files_guard();
drop trigger if exists lesson_files_no_update on public.lesson_files;
create trigger lesson_files_no_update before update on public.lesson_files for each row execute function private.lesson_chat_no_update();
drop trigger if exists lesson_files_no_delete on public.lesson_files;
create trigger lesson_files_no_delete before delete on public.lesson_files for each row execute function private.lesson_chat_no_direct_delete();

-- The log: no update at all, and no delete (a purged person's id is set null by the foreign key, which is an update of that column only).
create or replace function private.lesson_chat_log_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  if tg_op = 'UPDATE' then
    if (to_jsonb(new) - 'actor_profile_id') is distinct from (to_jsonb(old) - 'actor_profile_id') or new.actor_profile_id is not null then
      raise exception 'lesson_chat_access_log is append-only' using errcode = 'restrict_violation';
    end if;
    return new;
  end if;
  raise exception 'lesson_chat_access_log is append-only' using errcode = 'restrict_violation';
end;
$$;
drop trigger if exists lesson_chat_access_log_guard on public.lesson_chat_access_log;
create trigger lesson_chat_access_log_guard before update or delete on public.lesson_chat_access_log for each row execute function private.lesson_chat_log_guard();

