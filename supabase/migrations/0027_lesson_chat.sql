grant execute on function private.in_lesson(uuid), private.parent_of_finished_lesson(uuid), private.lesson_chat_no_direct_delete(), private.lesson_chat_no_update(),
  private.lesson_messages_guard(), private.lesson_messages_update_guard(), private.lesson_files_guard(), private.lesson_chat_log_guard() to authenticated, service_role;

