-- Is the caller part of this lesson as its tutor, or as a student enrolled in it (through their own learner login)?
create or replace function private.in_lesson(p_lesson uuid) returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
           select 1 from public.lessons l
            where l.id = p_lesson and l.tutor_id = private.my_tutor_id()
              and exists (select 1 from public.profile_roles r where r.profile_id = auth.uid() and r.role in ('TUTOR', 'JUNIOR_TUTOR'))
         )
      or exists (
           select 1 from public.lesson_students ls
             join public.learner_identities li on li.student_id = ls.student_id
            where ls.lesson_id = p_lesson and li.profile_id = auth.uid() and li.status = 'active'
         )
$$;

-- Is the caller a parent of a student on this lesson, and has the lesson finished? (A parent reads afterwards, never during.)
create or replace function private.parent_of_finished_lesson(p_lesson uuid) returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.lessons l
      join public.lesson_students ls on ls.lesson_id = l.id
     where l.id = p_lesson
       and private.student_in_my_family(ls.student_id)
       and now() >= l.start_at + make_interval(mins => l.duration_minutes)
  )
$$;

drop policy if exists lesson_messages_participant_read on public.lesson_messages;
create policy lesson_messages_participant_read on public.lesson_messages for select to authenticated
  using (removed_at is null and (private.in_lesson(lesson_id) or private.parent_of_finished_lesson(lesson_id)));

drop policy if exists lesson_files_participant_read on public.lesson_files;
create policy lesson_files_participant_read on public.lesson_files for select to authenticated
  using (
    exists (select 1 from public.lesson_messages m where m.id = lesson_files.message_id and m.removed_at is null)
    and (private.in_lesson(lesson_id) or private.parent_of_finished_lesson(lesson_id))
  );

-- The same execute rights as every other private function (0005): the policies call them as the signed-in user.
