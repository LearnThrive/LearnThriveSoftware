#!/usr/bin/env node
/**
 * Generates docs/ENVIRONMENT.md from scripts/env-registry.mjs, the single list of every variable the site reads. A test fails if the
 * committed file is out of date, so the document cannot drift from the code.
 *
 *   node scripts/env-docs.mjs            print it
 *   node scripts/env-docs.mjs --write    write docs/ENVIRONMENT.md
 *   node scripts/env-docs.mjs --template print a names-only .env.example (no values, no comments about values)
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { GROUPS, REGISTRY } from "./env-registry.mjs";

const cell = (text) => String(text).replace(/\|/g, "\\|");

export function renderEnvironmentDoc() {
  const lines = [
    "# Environment variables",
    "",
    "<!-- Generated by apps/web/scripts/env-docs.mjs from apps/web/scripts/env-registry.mjs. Do not edit by hand: change the registry and run `npm run env:docs`. -->",
    "",
    "Every variable the site, its scripts and its tools read, found by searching the code (a test fails if the code reads one that is not listed here). Values live in the host's dashboard (Render) and in a local `apps/web/.env` that is never committed. **No value, key, token or password belongs in the repository, a log, a document or a report.**",
    "",
    "Check an environment without showing a single value:",
    "",
    "```bash",
    "cd apps/web",
    "npm run check:env                      # your local environment (process.env plus apps/web/.env, whose contents are not shown)",
    "npm run check:env -- --env production  # what Render's environment should look like (run it in a shell that has those variables)",
    "```",
    "",
    "It reports each variable as present, absent, missing, malformed (wrong prefix, too short, a service key in the publishable slot, a local address in production) or, in production, forbidden or held. In a LOCAL environment it also fails any value that points at the hosted Supabase project: with the three Supabase variables present the site uses real Supabase, so a local file must only ever reach the local stack (`npm run supabase:start`). `CHECK_ENV_ALLOW_HOSTED=1` accepts it deliberately, for one run.",
    "",
    "## `apps/web/.env.example`",
    "",
    "It must hold **names only**. It is not edited by hand or by the assistants that wrote this repository (access to `.env*` files is blocked for them). Regenerate it from the registry, review the diff, and commit it:",
    "",
    "```bash",
    "cd apps/web",
    "node scripts/env-docs.mjs --template > .env.example   # (not `npm run`: npm prints its own banner into the file)",
    "```",
    "",
    "## Local development",
    "",
    "Nothing is required for the ordinary site: leave `apps/web/.env` with only the mail settings you want to try. To run on the real Supabase stack locally, start it (`npm run supabase:start`) and set these three, to the LOCAL values `npx supabase status` prints (they are not secrets for any real project):",
    "",
    "```text",
    "SUPABASE_URL=http://127.0.0.1:54321",
    "SUPABASE_ANON_KEY=<the local publishable key>",
    "SUPABASE_SERVICE_ROLE_KEY=<the local secret key>",
    "DATABASE_URL=postgresql://postgres:postgres@127.0.0.1:54322/postgres",
    "```",
    "",
    "## Render (production)",
    "",
    "Set these in Render's environment, as secrets where the table says so, and nowhere else. The browser never receives any of them: the only variables that reach a page are the `NEXT_PUBLIC_*` ones, none of which is secret (a test checks the code and the built output).",
    "",
    "- **Required to run:** " + REGISTRY.filter((v) => v.production === "required").map((v) => `\`${v.name}\``).join(", ") + ".",
    "- **Stay unset until the owner flips them** (each opens something that is closed by default): " + REGISTRY.filter((v) => v.held).map((v) => `\`${v.name}\``).join(", ") + ". In particular `LIBRARY_ENABLED` and `NEXT_PUBLIC_APP_PORTAL_ENABLED` are not set as part of the Supabase work.",
    "- **Never set in production** (development, tests or an operator's own shell): " + REGISTRY.filter((v) => v.production === "unset").map((v) => `\`${v.name}\``).join(", ") + ".",
    "- **Secret:** " + REGISTRY.filter((v) => v.secret).map((v) => `\`${v.name}\``).join(", ") + ".",
    "",
  ];
  for (const [group, title] of GROUPS) {
    lines.push(`## ${title}`, "", "| Variable | What it does | Local | Render production | Secret | Where you get it | If unset |", "| --- | --- | --- | --- | --- | --- | --- |");
    for (const v of REGISTRY.filter((x) => x.group === group)) {
      lines.push(`| \`${v.name}\` | ${cell(v.purpose)} | ${cell(v.local)} | ${cell(v.production)} | ${v.secret ? "**yes**" : "no"} | ${cell(v.source || "n/a")} | ${cell(v.fallback)} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

export function renderTemplate() {
  const out = ["# Names only: no values belong in this file. Copy to apps/web/.env and fill in what you need.", "# Generated by apps/web/scripts/env-docs.mjs --template from the registry; docs/ENVIRONMENT.md explains each one.", ""];
  for (const [group, title] of GROUPS) {
    out.push(`# ${title}`);
    for (const v of REGISTRY.filter((x) => x.group === group)) if (v.name !== "NODE_ENV" && v.name !== "CI") out.push(`# ${v.name}=`);
    out.push("");
  }
  return out.join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  if (args.includes("--template")) process.stdout.write(renderTemplate());
  else if (args.includes("--write")) {
    const target = fileURLToPath(new URL("../../../docs/ENVIRONMENT.md", import.meta.url));
    writeFileSync(target, renderEnvironmentDoc());
    console.log("Wrote docs/ENVIRONMENT.md");
  } else process.stdout.write(renderEnvironmentDoc());
}
